DROP POLICY IF EXISTS "customers_select_assigned_or_admin" ON public.customers;
CREATE POLICY "customers_select_assigned_or_admin" ON public.customers FOR SELECT TO authenticated
USING (assigned_to = auth.uid() OR is_admin_user() OR has_role('auditor'));

DROP POLICY IF EXISTS "customers_insert_authenticated" ON public.customers;
CREATE POLICY "customers_insert_authenticated" ON public.customers FOR INSERT TO authenticated
WITH CHECK (created_by = auth.uid() AND (assigned_to IS NULL OR assigned_to = auth.uid() OR is_admin_user()));

DROP POLICY IF EXISTS "customers_update_assigned_or_admin" ON public.customers;
